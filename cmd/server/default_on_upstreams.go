// default_on_upstreams.go —— 把"上游 enabled"的缺省值从 false 翻成 true。
//
// # 用户的要求（原话）
//
//	「或者你直接这样吧：不要有启动或者不启动了，默认全部启动。」
//
// # 为什么保留 `enabled` 字段（而不是删掉）
//
// 删掉它就没有逃生口了。三个真实场景需要关掉某个上游：
//
//	① 那个上游的凭证全失效了，账号池里全是死号 —— 关掉才能让
//	   「账号不可用」的告警安静下来
//	② 想临时停掉一个上游（风控期、维护期）
//	③ 只用一个上游的极简部署（想让 `GET /v1/models` 干净）
//
// 所以语义是：**缺省开，显式 `false` 才关**。
//
// # ⚠ 这不是"改个默认值"那么简单 —— 它是**兼容性反转**
//
// 改之前，`"enabled"` 缺席 = 关；改之后，缺席 = 开。
// 于是"以前**故意**不写 enabled 来关掉某上游"的配置，
// 升级后会**变成打开** —— 而用户不会收到任何提示。
//
// 这一条必须在 CHANGELOG 里写明，并且启动时对"从 false 翻成 true"的
// 每个上游**单独打一行日志** —— 静默把一个上游打开始终是意外行为，
// 哪怕那是用户要求的新缺省。
//
// # 为什么用 `*bool` + `boolOr`
//
// `bool` 的零值也是 false，无法区分"没写"与"写了 false"。
// 本仓已有这个惯用法（`Trae.CheckinEnabled` / `Codearts.WelfareEnabled`
// 都是 `*bool` + `boolOr(..., true)`），这里沿用同一套 —— 不引入新范式。
package main

// upstreamEnableDefault 是"上游缺省是否启用"的唯一事实来源。
//
// 它存在的原因不是配置，而是**日志**：启动时要能回答
// 「这个上游为什么开着 / 为什么关着」，而"缺省开"这个事实
// 如果不集中在一处，就会散成 10 个 `boolOr(c.X.Enabled, true)`，
// 日后有人漏改一个（或手滑写成 false）没有任何测试能发现。
//
// 由 default_on_upstreams_test.go 守住：它逐个断言每个上游在
// **完全缺席**的配置下都是启用的。
const upstreamEnableDefault = true
