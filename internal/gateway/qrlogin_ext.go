// qrlogin_ext.go 上游自报"我的登录链接要**扫码**，不是点开"。
//
// # 为什么需要这个扩展点（用户报的缺陷）
//
// raccoon（商汤小浣熊）的登录是**微信扫码**：`Start()` 返回的是一个
// **要扫的 URL**（`https://xiaohuanxiong.com/login/mp?code=<32位hex>`），
// 而不是一个"点开就能授权"的网页。
//
// 而前端此前对**所有**上游只渲染「打开授权页 / 复制链接」——
// 用户拿到一条链接，无法扫码（链接在屏幕上，手机扫不了自己的屏幕），
// 于是 raccoon 的「＋ 添加账号」等于不可用。
//
// 参照项目（dsh-codearts-auth 的 raccoon-login-page.ts + raccoon-qr.ts）
// 的解法是：宿主侧把该 URL 渲染成**二维码**（内联 SVG）放进它的登录页。
// 本网关是纯后端、没有那个页面，所以由**上游**声明"我是扫码流程"，
// 核心据此把二维码 SVG 一起下发，前端插进 DOM 即可。
//
// # 为什么不让前端自己判断"这是不是个二维码 URL"
//
// 那需要前端认识上游名或 URL 形态 —— 两者都是本项目最硬的禁忌
//（"加一个上游时前端一行都不该改"）。而且判断错了不会报错，
// 只会静默渲染出一个扫不了的链接，正是当前这个缺陷的形态。
//
// # 为什么返回 SVG 字符串而不是"要不要画二维码"的布尔
//
// 二维码的内容与尺寸由**上游**决定（它才知道该编码什么、多大合适），
// 核心只负责搬运。返回布尔会让核心不得不去猜内容 —— 那是认识上游。
package gateway

// QRLoginExt 上游自报"我的登录链接要**扫码**，不是点开"。
type QRLoginExt interface {
	// QRLoginSVG 返回本次登录要展示的二维码（内联 SVG 字符串）。
	//
	// authURL 是本次 `Start()` 返回的那个链接 —— 实现方应当把它编码成
	// 二维码。返回空串表示"本次不展示二维码"（例如非扫码流程）。
	//
	// ⚠ 内容过长时应当返回空串并让调用方回落到"显示链接"，
	// 而不是产出一个扫不出来的坏码 —— 后者表现为"用户扫码没反应"，
	// 没有任何迹象指向编码器。
	QRLoginSVG(authURL string) string
}
