package gateway

// quota_consumed.go 上游"我消耗了额度"的上报口。
//
// # 为什么需要它（而不是让上游直接改池子）
//
// 上游的 `Chat` 能从回执里读到"这次花了多少"（见 usagetap.go），但
// **扣减发生在哪**是个架构问题：
//
//	额度的真相在核心的账号池里（`pool.SetQuota`）
//	而**上游不允许 import 核心**（arch_test.go 守着这条接缝）
//
// 所以走"上报"：上游只负责算出"这个账号少了几个**显示单位**"，核心决定怎么
// 用它（写进池子 / 记日志 / 什么都不做）。
//
// # ⚠ 为什么上报的是**显示单位**而不是上游的原始小数
//
// 实测：qoder 的消耗是 `0.006352698571428571` credits/次，而它的池子显示值
// 是 `int64(Total)` —— **整数 credits**。若把小数上报给核心，核心不知道刻度、
// 也没法扣（扣 0.006 等于没扣）。
//
// 所以由**上游自己**在内部累计小数、只在**跨过整数**时上报 ——
//
//	核心不需要知道任何上游的刻度
//	显示值保持上游自己的单位（用户对 qoder 明确要求过"显示原始值不换算"）
//
// # ⚠ 一个已知的、自愈的偏差
//
// 上游累计的是"上次查询之后的消耗"。若在它上报之前核心刚好做了一次
// `RefreshQuota`（拿到的是**已经包含**那些消耗的真实余额），那次上报就会
// **多扣**一次。
//
// 上游的处置：`RefreshQuota` 成功时**清空**该 uid 的待上报累计（那次查询
// 就是新基准）。所以偏差最多存在到下一次刷新，是**有界且自愈**的。
// 如实写在这里，而不是假装没有。
type QuotaConsumedSink interface {
	// OnQuotaConsumed 报告：provider 的 uid 这个账号刚刚消耗了 wholeUnits 个
	// **显示单位**（credits / 积分，与 `QuotaView.Remaining` 同单位）。
	//
	// ⚠ 实现必须**非阻塞、不返回错误、可被并发调用** —— 它在转发路径上被调用
	//（流结束时），任何阻塞都会拖住对话收尾。
	//
	// ⚠ 实现必须自己判断"这个账号的额度形态能不能减"：`unlimited` / `per_model`
	// 没有"一个可减的数"，硬减就是编数据。
	OnQuotaConsumed(provider, uid string, wholeUnits int64)
}
