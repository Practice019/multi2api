// candidate_tier.go —— 上游自报「这批候选账号我更想先用哪个」。
//
// # 为什么核心需要这个扩展点（用户报的一个真实缺陷）
//
// Loomy 的额度模型与其它上游不同，有**两个并行的账本**：
//
//	balance       总余额  —— 不随自然日重置（邀请/活动/充值累积）＝"永久额度"
//	dailyBalance  每日额度 —— 服务端按自然日重置为 5000，**不用就浪费**
//
// 用户的要求（原话）：
//
//	「优先使用免费额度，轮询所有账号，把所有账号的免费额度用完之后，
//	  它才能用永久的额度。如果说有一个账号的免费额度用完了，
//	  那就轮询下一个账号，直到所有的账号免费额度都没有了，才能用永久额度。」
//
// 而 Loomy **不会**因额度耗尽报错 —— 服务端是**静默降级**（继续扣永久积分
// 且照常返回 200）。所以本仓既有的"按限流错误换号"机制对它**完全无效**：
// 它会一直烧同一个号的永久积分，而核心永远不会知道该换号。
//
// 也就是说：这个需求**不能**靠"等上游报错再换号"实现 —— 必须在**选号时**
// 就按余额把候选分开。
//
// # 为什么是一个"分档"接口，而不是让核心理解"免费/永久"
//
// 「每日赠送额度用完就该换号」是 **Loomy 独有的事实**。核心既不知道什么是
// 免费额度，也不该知道 —— 那是上游的账本语义。核心只需要一个通用能力：
//
//	「把这批候选按优先级分成几档，先用最好的那档」
//
// 分档的**内容**由上游决定，核心只负责"只用最好那一档的账号"。
//
// # 与「候选过滤」的分工（调用方必须遵守）
//
// 候选集由**调用方**先行过滤（未停用 + 该模型未受限 + 未在本次重试里失败过），
// 本接口**不再过滤**，只做分档。理由：过滤是核心的既有职责（它才知道
// 冷却/熔断/在途/模型限流），而上游不该重复实现它。
//
// # ⚠ 实现约束：必须是**纯本地**判断（这条最要紧）
//
// 调用方在**持有账号池锁**的状态下调用本方法（选号路径）。若实现里发网络
// 请求（例如逐个账号查余额），会把整个池子的选号串行阻塞住 ——
// N 个账号 × 每次超时，等于整个网关停摆。
//
// 所以实现必须读**自己的缓存**，缓存由后台/懒刷新填充。
// 这与 `RefreshSkewExt` 的约束同型（那个也在出站路径上被调用）。
package gateway

// CandidateTierExt 上游自报「候选账号的优先级分档」。
//
// 与 `QuotaExt` / `HealthProbeExt` 同构：核心只问、不判断。
type CandidateTierExt interface {
	// CandidateTiers 返回每个候选 uid 的档位号。
	//
	// # 返回值语义
	//
	//	数字**越小越优先**；调用方只保留"最小值那一档"的候选。
	//	未出现在返回 map 里的 uid 视为**最低优先级**（与"未知"同档）。
	//
	// 实现方可以自由定义档位含义，但必须满足三条（用户明确要求）：
	//
	//  1. **档内不排序**。本方法只回答"谁属于哪一档"，**不得**试图表达
	//     "档内谁更优先" —— 档内顺序由调用方按它既有的策略（加权/轮询）
	//     决定。用户对既有选号策略没有意见，改的只是跨档优先级。
	//  2. **"查不到"归最后的档**，不是第一档。宁可先用能确认余额的账号 ——
	//     把未知当成"最优"会让网关拿不准的账号去烧额度。
	//  3. **不为空判断兜底**：若整批候选都拿不到档位信息，返回空 map，
	//     调用方会退化成既有行为（不改变任何东西）。
	//
	// # 参数
	//
	//	model  本次请求的模型（可能为空串）。分档**可以**因模型而异
	//	       （本仓的限流是按模型记的），但 Loomy 的账本与模型无关。
	//	uids   候选 uid 列表。**只对这些 uid 回答**，不要多返回其它 uid。
	//
	// # 为什么返回 map 而不是"排序后的列表"
	//
	// 排序后的列表会**诱导**实现方在档内排序（把"优先级"和"档位"混成
	// 一件事），而档内顺序是调用方的职责。map 只能表达"属于哪档"，
	// 让边界在类型上就清楚。
	CandidateTiers(model string, uids []string) map[string]int
}
