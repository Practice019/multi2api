// refresh_skew.go —— 第六个扩展点：上游自报「多早算该刷」。
//
// # 为什么必须有这个扩展点（这是出站修复的一个漏网）
//
// `CredentialRefresher` 修好了「**怎么**刷新我的凭证」，但「**要不要**刷」
// 仍然留在核心：出站循环先做
//
//	if acct.NeedsRefresh(h.cfg.RefreshSkew)   // 默认 10m
//
// 只有它返回 true 才会走到上游的续期实现。于是核心用一个**通用窗口**
// 替所有上游回答了"多早算该刷" —— 而这是**上游的事实**：
//
//	workbuddy → access token 寿命以小时计，10 分钟窗口合理
//	codearts  → STS 凭证只有约 30 分钟寿命，它自己的窗口是 3m
//
// # 10m 对 codearts 具体错在哪
//
// 两个方向都是错的，而且**方向相反**：
//
//	剩 8m  → 核心判 true（10m 窗口）→ 进续期分支。
//	         codearts 的 CredentialRefresher 里**没有** skew 检查
//	         （它只做断言+转发，见 codearts/credentialrefresher.go），
//	         于是真的去消费 refresh_token —— 而 codearts 的 refresh_token
//	         是**一次性**的（用一次即作废）。为省一次 401 往返烧掉一个凭证。
//
//	剩 4m  → 若某上游的窗口比 10m 更宽，核心判 false → 永不续期 → 必然 401。
//
// 这不是"两个规则冲突时谁赢"的问题 —— 是**只有一个规则该存在**。
// 核心没有"赢"的资格：它不知道任何上游的凭证寿命。
//
// # 与 CredentialRefresher 的分工（两者必须成对）
//
//	CredentialRefresher  → 「怎么刷」（DPoP 签名、持锁、一次性消费的语义）
//	RefreshSkewExt       → 「多早刷」（该上游凭证寿命决定的窗口）
//
// 拆成两个扩展点而不是给 CredentialRefresher 加一个方法，是因为
// 「需要续期」与「需要**提前**续期」是两件事：一个上游完全可能
// 实现了续期（被动、401 之后）却**不需要**提前窗口（返回 0）。
//
// ⚠ 没实现本扩展点的上游**不算错**：核心回落到自己的通用兜底窗口
// （见 handler.go 的 refreshNeeded）。这是明确的保守兜底，
// 不是"核心假装知道上游的寿命"。
//
// # 为什么参数是 Credential 而不是 uid
//
// 与 CredentialRefresher 同理：窗口可能取决于凭证本身（例如不同
// 凭证类型寿命不同），而核心**不得读** Credential.Secret。
// 上游拿到整份凭证自己断言类型。
package gateway

import "time"

// RefreshSkewExt 上游自报「我的凭证多早算该刷」。
//
// 与 CredentialRefresher 成对：一个说怎么刷，一个说什么时候该刷。
// 两者都由**上游**回答，核心只问、不判断。
type RefreshSkewExt interface {
	// RefreshSkew 返回该凭证的提前刷新窗口。
	//
	// # 返回值语义
	//
	//	skew > 0  → 距过期不足 skew 时应当提前续期
	//	skew == 0 → **不需要**提前续期（仅在收到 401 后被动续期）
	//	ok == false → 本上游**没有**上报窗口，调用方回落到自己的通用兜底
	//
	// ⚠ 必须区分「返回 0」与「ok=false」：
	//
	//	返回 0    是上游的一个**明确声明**（"我这不需要提前窗口"）——
	//	          调用方必须尊重它，不能拿通用窗口覆盖。
	//	ok=false  是上游**没有这个信息** —— 调用方用兜底值是合理的。
	//
	// 把两者混成一个（例如用 0 同时表示"不需要"和"不知道"）会让
	// 「明确不需要提前刷」的上游被强加上一个通用窗口，
	// 那正是本扩展点要修的那类错误。
	//
	// # 实现约束
	//
	// 必须是**纯本地**判断（只读凭证里的过期时刻），不得发网络请求 ——
	// 它在出站循环的**每次**请求上被调用（每个候选账号一次）。
	//
	// 窗口必须显著小于凭证寿命：codearts 的 30 分钟寿命配 3m 窗口，
	// 若窗口接近寿命会出现"刚判定为新鲜、发出去已过期"。
	RefreshSkew(cred Credential) (skew time.Duration, ok bool)
}
