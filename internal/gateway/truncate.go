package gateway

// truncate.go —— 「把上游响应体截短塞进错误日志」这件小事的**唯一**实现（T-234）。
//
// # 为什么必须共享
//
// 这份逻辑原先在 5 个上游包各写了一份，**逐字相同**：
// `cline/client.go:85` · `lobsterai/client.go:84` · `monkeycode/client.go:529` ·
// `qoder/client.go:118` · `raccoon/client.go:56`
//
//	func truncate(s string, n int) string {
//		if len(s) <= n { return s }
//		return s[:n] + "…"
//	}
//
// 复制 5 份的代价不是行数，是**改一处漏四处**。上提到这里之后，
// 全仓只留 `Truncate` 一份定义（另有 6 处**语义不同**的同名函数，见文末）。
//
// # 为什么是「字节」而不是「rune」
//
// ⚠ 这里**故意**保持字节语义（与那 5 份原件一致，本函数是**行为等价**的重构）：
// 调用点全在"上游 N 字节的响应体 → 错误日志"这条路上，长度参数（160/200/300）
// 本来就是按字节估的。截断点落在多字节字符中间时，日志里会出现半个汉字 ——
// 那不是"我们制造了乱码"，而是"**这里确实被切了**"的可见信号。
//
// 若将来有调用点需要"给人看的短文本"（而不是日志），**不要改这里** ——
// 另加 `TruncateRunes`，让两种意图各自显式。
//
// # 与另外 6 处同名函数的区别（刻意不合并）
//
// 全仓还有 6 个叫 truncate 的函数，语义**各不相同**，合并会改变行为：
//
//	codearts/client.go:827 · oauth/oauth.go:390   → 先把 \n 换成空格，且超长时**不加省略号**
//	trae/client.go:649     · upstream/client.go:890 → 先 TrimSpace，且超长时**不加省略号**
//	openaicompat/util.go:18                        → 回退到 UTF-8 合法边界（**不切坏字符**）
//	cmd/auditreport/main.go:417                    → 按 **rune** 截断
//
// 它们是四种不同意图，不是同一个函数的四份复制。要合并得先逐个确认
// "调用点是否依赖那个差异"，那是另一件事（见 T-234 报告）。

// Truncate 把 s 截到最多 n 个**字节**；超长时在末尾补一个省略号。
//
// 与原件唯一的差异：`n <= 0` 时**原样返回 s**（原件会给非空 s 返回 "…"）。
// 实测 27 个调用点的 n 都是 160/200/300，这个分支永远不会被走到；
// 保留它只是为了让"n 传了 0 就吐一个省略号"这种傻结果不至于出现。
func Truncate(s string, n int) string {
	if n <= 0 || len(s) <= n {
		return s
	}
	return s[:n] + "…"
}
