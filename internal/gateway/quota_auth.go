package gateway

// QuotaAuthFailureExt 上游自报「上一次额度查询失败，是不是因为**凭据失效**」。
//
// # 为什么需要这个扩展点（契约缺口）
//
// `QuotaExt.RefreshQuota` 只回 `(QuotaView, ok)` —— **没有错误原文**。
// 于是核心拿不到"这次失败是账号问题还是网络问题"的判据，而这两者的处置相反：
//
//	账号过期   ⇒ 该摘号（否则每次刷新都白打一次，界面上也看不出原因）
//	网络抖动   ⇒ **绝不能**摘号（一次上游故障会把整池号刷成禁用）
//
// 用 `ok=false`（Failed）当判据也不行：按契约它表示"账号不存在 / 未接线"，
// 而 loomy 的失败路径统一返回 `UnknownQuota(), true`（HasData=false）——
// 与"本机没有客户端目录""uid 不匹配"这些**正常情况**共用同一个返回值。
//
// 所以这条判据**只能由上游给出**：它看得见上游的响应原文。
// 这与错误分类器同一条原则（"上游的语义只能由上游自己解释"；判例见
// gateway.ErrorClassifier 的包注释）。
//
// # 机制
//
// 与其它扩展点一致：上游只实现自己有的，核心用类型断言发现。
// **没有实现的上游**什么都不发生（既不摘号也不恢复）—— 纯增量、可选。
type QuotaAuthFailureExt interface {
	// QuotaAuthFailed 报告该账号**最近一次**额度查询是否因凭据失效而失败。
	//
	// 语义是"上一次查询的结论"，不是"这个号的永久属性"：
	// 下一次查询成功就必须把它清掉（否则一个重登后的号会被一直误判）。
	//
	// 必须纯函数：只读自己记录的状态，**不发网络请求**
	//（调用方在一次刷新的收尾处问它，那时每次查询都已经跑完了）。
	QuotaAuthFailed(uid string) bool
}
